CREATE FUNCTION public.json_array_length(t text) RETURNS integer
    LANGUAGE plpgsql IMMUTABLE
    AS $$
BEGIN
  IF t IS NULL OR NOT (t IS JSON) THEN RETURN 0; END IF;
  RETURN json_array_length(t::json);
EXCEPTION WHEN OTHERS THEN RETURN 0;
END $$;

CREATE FUNCTION public.json_each(t text) RETURNS TABLE(value text)
    LANGUAGE plpgsql IMMUTABLE
    AS $$
BEGIN
  IF t IS NULL OR NOT (t IS JSON) THEN RETURN; END IF;
  RETURN QUERY SELECT elem FROM json_array_elements_text(t::json) AS elem;
EXCEPTION WHEN OTHERS THEN RETURN;
END $$;

CREATE FUNCTION public.json_valid(t text) RETURNS integer
    LANGUAGE plpgsql IMMUTABLE
    AS $$
BEGIN
  IF t IS NULL THEN RETURN 0; END IF;
  RETURN CASE WHEN t IS JSON THEN 1 ELSE 0 END;
END $$;

CREATE FUNCTION public.v3_guard_cover_media_delete() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM works
        WHERE id=OLD.work_id AND cover_media_id=OLD.media_id
    ) THEN
        RAISE EXCEPTION 'cannot_remove_cover_media';
    END IF;
    RETURN OLD;
END $$;

CREATE FUNCTION public.v3_guard_generation_item_media() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
    IF NEW.media_id IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM generation_runs r
        JOIN media_assets m ON m.id=NEW.media_id
        WHERE r.id=NEW.run_id AND r.user_id=m.owner_user_id
    ) THEN
        RAISE EXCEPTION 'generation_item_owner_mismatch';
    END IF;
    RETURN NEW;
END $$;

CREATE FUNCTION public.v3_guard_work_cover() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
    IF NEW.cover_media_id IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM work_media
        WHERE work_id=NEW.id AND media_id=NEW.cover_media_id
    ) THEN
        RAISE EXCEPTION 'cover_must_be_linked_media';
    END IF;
    RETURN NEW;
END $$;

CREATE FUNCTION public.v3_guard_work_images_cache() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
DECLARE canonical jsonb;
BEGIN
    IF NEW.run_id IS NULL THEN RETURN NEW; END IF;
    SELECT COALESCE(jsonb_agg(m.storage_key ORDER BY wm.position), '[]'::jsonb)
    INTO canonical
    FROM work_media wm JOIN media_assets m ON m.id=wm.media_id
    WHERE wm.work_id=NEW.id;
    IF COALESCE(NEW.images_json,'[]')::jsonb IS DISTINCT FROM canonical THEN
        RAISE EXCEPTION 'generated_work_media_cache_mismatch';
    END IF;
    RETURN NEW;
END $$;

CREATE FUNCTION public.v3_guard_work_media_owner() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM works w JOIN users u ON u.username=w.author_username
        JOIN media_assets m ON m.id=NEW.media_id
        WHERE w.id=NEW.work_id AND m.owner_user_id=u.id
    ) THEN
        RAISE EXCEPTION 'work_media_owner_mismatch';
    END IF;
    RETURN NEW;
END $$;

CREATE FUNCTION public.v3_guard_work_run() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
    IF NEW.run_id IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM generation_runs r
        JOIN users u ON u.id=r.user_id
        WHERE r.id=NEW.run_id AND u.username=NEW.author_username
    ) THEN
        RAISE EXCEPTION 'work_run_owner_mismatch';
    END IF;
    RETURN NEW;
END $$;

CREATE FUNCTION public.v3_immutable_generation_run() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
    IF NEW.user_id IS DISTINCT FROM OLD.user_id OR
       NEW.source IS DISTINCT FROM OLD.source OR
       NEW.external_run_id IS DISTINCT FROM OLD.external_run_id THEN
       RAISE EXCEPTION 'run_identity_is_immutable';
    END IF;
    RETURN NEW;
END $$;

CREATE FUNCTION public.v3_immutable_media_identity() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
    IF NEW.owner_user_id IS DISTINCT FROM OLD.owner_user_id OR
       NEW.storage_key IS DISTINCT FROM OLD.storage_key THEN
       RAISE EXCEPTION 'media_identity_is_immutable';
    END IF;
    RETURN NEW;
END $$;

