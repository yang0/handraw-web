CREATE TABLE IF NOT EXISTS public.payment_orders (
    id TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(id),
    provider TEXT NOT NULL DEFAULT 'lemonsqueezy',
    pack_id TEXT NOT NULL,
    variant_id TEXT NOT NULL DEFAULT '',
    credits BIGINT NOT NULL,
    amount_cents BIGINT NOT NULL DEFAULT 0,
    currency TEXT NOT NULL DEFAULT 'CNY',
    status TEXT NOT NULL DEFAULT 'pending',
    checkout_id TEXT NOT NULL DEFAULT '',
    checkout_url TEXT NOT NULL DEFAULT '',
    provider_order_id TEXT NOT NULL DEFAULT '',
    provider_order_number TEXT NOT NULL DEFAULT '',
    test_mode BIGINT NOT NULL DEFAULT 0,
    meta_json TEXT NOT NULL DEFAULT '{}',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    paid_at TEXT
);
CREATE INDEX IF NOT EXISTS idx_payment_orders_user
    ON public.payment_orders(user_id, created_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS idx_payment_orders_provider_order
    ON public.payment_orders(provider, provider_order_id)
    WHERE provider_order_id <> '';

CREATE TABLE IF NOT EXISTS public.payment_webhook_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider TEXT NOT NULL DEFAULT 'lemonsqueezy',
    event_key TEXT NOT NULL,
    event_name TEXT NOT NULL,
    provider_order_id TEXT NOT NULL DEFAULT '',
    signature_valid BIGINT NOT NULL DEFAULT 0,
    payload_json TEXT NOT NULL DEFAULT '{}',
    status TEXT NOT NULL DEFAULT 'processed',
    created_at TEXT NOT NULL,
    UNIQUE(provider, event_key)
);

