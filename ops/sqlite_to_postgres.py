#!/usr/bin/env python3
"""Stage a read-only Handraw SQLite snapshot in a fresh PostgreSQL database.

This is an explicit STAGING / parity-validation tool, not a transparent engine
switch. It preserves every row, including historical password hashes and
Discourse-imported usernames, email verification and oauth identities. It
never reads plaintext passwords or creates replacement accounts.

Safety:
- Source SQLite is opened mode=ro and queried only.
- The PostgreSQL target must be completely empty (public schema except extensions).
- No REPLACE, TRUNCATE, DROP or overwrites.
- Failed import rolls back the entire database transaction.
- The source may have SQLite triggers and business-specific SQL; this tool does
  not port them to PostgreSQL and does NOT declare runtime readiness.
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import json
import os
import re
import sqlite3
import sys
from collections import defaultdict
from pathlib import Path
from urllib.parse import urlsplit

try:
    import psycopg
    from psycopg import sql
except ImportError:
    psycopg = None
    sql = None


def q(value: str):
    if not re.fullmatch(r"[A-Za-z_][A-Za-z_0-9]*", value):
        raise ValueError("Invalid SQL identifier in source schema")
    return sql.Identifier(value)


def read_snapshot(path: Path) -> tuple[sqlite3.Connection, list[str]]:
    if not path.is_file():
        raise ValueError("SQLite snapshot does not exist")
    conn = sqlite3.connect(path.as_uri() + "?mode=ro", uri=True, timeout=10)
    conn.row_factory = sqlite3.Row
    check = conn.execute("PRAGMA integrity_check").fetchone()[0]
    if check != "ok":
        conn.close()
        raise ValueError("Source SQLite failed integrity_check: " + str(check)[:120])
    fk_issues = conn.execute("PRAGMA foreign_key_check").fetchall()
    if fk_issues:
        conn.close()
        raise ValueError("Source SQLite has orphan foreign keys (count=%d)" % len(fk_issues))
    names = [row["name"] for row in conn.execute(
        "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name"
    ).fetchall()]
    if "users" not in names or "sessions" not in names:
        conn.close()
        raise ValueError("Source does not look like a Handraw v2 database")
    return conn, names


def _table_columns(conn: sqlite3.Connection, table: str) -> list[sqlite3.Row]:
    return list(conn.execute('PRAGMA table_info("%s")' % table).fetchall())


def _foreign_keys(conn: sqlite3.Connection, table: str) -> list[sqlite3.Row]:
    return list(conn.execute('PRAGMA foreign_key_list("%s")' % table).fetchall())


def _source_counts(conn, tables):
    return {table: conn.execute('SELECT COUNT(*) FROM "%s"' % table).fetchone()[0]
            for table in tables}


def _sqlite_type(t: str, *, generated: bool = False) -> str:
    t = t.upper().strip()
    if generated:
        return "BIGINT GENERATED BY DEFAULT AS IDENTITY"
    if "INT" in t:
        return "BIGINT"
    if "CHAR" in t or "CLOB" in t or "TEXT" in t or t == "":
        return "TEXT"
    if "BLOB" in t:
        return "BYTEA"
    if "REAL" in t or "FLOA" in t or "DOUB" in t:
        return "DOUBLE PRECISION"
    if "NUMERIC" in t or "DECIMAL" in t:
        return "NUMERIC"
    return "TEXT"


def inspect_schema(conn, tables, *, allow_omitting_nonunique_expressions=False):
    columns, foreign_keys, unique_indexes, identity = {}, [], [], {}
    for table in tables:
        cols = _table_columns(conn, table)
        if not cols:
            raise ValueError("Table has no regular columns: " + table)
        create_sql = conn.execute(
            "SELECT sql FROM sqlite_master WHERE type='table' AND name=?", (table,)
        ).fetchone()["sql"]
        columns[table] = cols
        for col in cols:
            if (col["pk"] == 1 and len([c for c in cols if c["pk"]]) == 1
                    and re.search(r'\b"?'+re.escape(col["name"])+r'"?\s+INTEGER\s+PRIMARY\s+KEY\b',
                                  create_sql, re.I)):
                identity[table] = col["name"]
        foreign_keys.extend([(table, row) for row in _foreign_keys(conn, table)])
        for index in conn.execute('PRAGMA index_list("%s")' % table):
            if index["origin"] == "pk":
                continue
            index_name = index["name"]
            index_cols = conn.execute('PRAGMA index_xinfo("%s")' % index_name).fetchall()
            real_cols = [r["name"] for r in index_cols if r["key"] and r["cid"] >= 0]
            expressions = [r for r in index_cols if r["key"] and r["cid"] < 0]
            if expressions:
                # Port only the audited arithmetic popularity index. Any other
                # expression must be reviewed rather than silently discarded.
                if table == "works" and index_name == "idx_works_popular_v3":
                    unique_indexes.append((table, index_name, [], "", False))
                    continue
                if allow_omitting_nonunique_expressions and not index["unique"]:
                    # Fresh-schema bootstrap may omit SQLite-only *performance*
                    # expression indexes. Never skip a uniqueness constraint.
                    continue
                raise ValueError("Expression index requires explicit PostgreSQL port: " + index_name)
            index_ddl_row = conn.execute(
                "SELECT sql FROM sqlite_master WHERE type='index' AND name=?", (index_name,)
            ).fetchone()
            index_ddl = (index_ddl_row["sql"] if index_ddl_row else "") or ""
            partial = ""
            if index["partial"]:
                matched = re.search(r"\bWHERE\s+(.+)$", index_ddl, re.I | re.S)
                if not matched:
                    raise ValueError("Cannot translate SQLite partial index " + index_name)
                partial = matched.group(1).strip()
                if re.search(r"strftime|json_extract|julianday|datetime\s*\(", partial, re.I):
                    if allow_omitting_nonunique_expressions and not index["unique"]:
                        continue
                    raise ValueError("SQLite-only unique index: " + index_name)
            unique_indexes.append((table, index_name, real_cols, partial, bool(index["unique"])))
    return columns, foreign_keys, unique_indexes, identity


def _is_nocase_column(conn, table: str, column: str) -> bool:
    source = conn.execute(
        "SELECT sql FROM sqlite_master WHERE type='table' AND name=?", (table,)
    ).fetchone()["sql"]
    for line in source.splitlines():
        if re.search(r'^\s*"?'+re.escape(column)+r'"?\s+', line, re.I):
            return bool(re.search(r'\bCOLLATE\s+NOCASE\b', line, re.I))
    return False


def _defaults(col, source_create):
    value = col["dflt_value"]
    if value is None:
        return ""
    v = str(value).strip()
    # Keep constants, including empty strings and literal JSON. Reject computed
    # SQLite expressions rather than silently losing their semantics.
    if re.fullmatch(r"-?\d+(?:\.\d+)?|NULL|TRUE|FALSE|'(?:[^']|'')*'", v, re.I):
        return " DEFAULT " + v
    if v.startswith("(") and v.endswith(")"):
        inner = v[1:-1]
        if re.fullmatch(r"-?\d+(?:\.\d+)?|NULL|'(?:[^']|'')*'", inner, re.I):
            return " DEFAULT " + inner
    raise ValueError("Computed SQLite default needs manual PostgreSQL mapping")


def build_tables(cur, conn, tables, cols, identity):
    for table in tables:
        specs = []
        pk_cols = [c["name"] for c in sorted(cols[table], key=lambda c: c["pk"]) if c["pk"]]
        for c in cols[table]:
            generated = identity.get(table) == c["name"]
            dtype = "CITEXT" if _is_nocase_column(conn, table, c["name"]) else _sqlite_type(c["type"], generated=generated)
            clause = sql.SQL("{} {}{}{}").format(
                q(c["name"]), sql.SQL(dtype),
                sql.SQL("" if generated else _defaults(c, "")),
                sql.SQL(" NOT NULL" if c["notnull"] and not generated else ""),
            )
            specs.append(clause)
        if pk_cols:
            specs.append(sql.SQL("PRIMARY KEY ({})").format(
                sql.SQL(",").join(q(name) for name in pk_cols)
            ))
        cur.execute(sql.SQL("CREATE TABLE {} ({})").format(
            q(table), sql.SQL(",").join(specs)
        ))


def import_rows(cur, conn, tables, cols):
    for table in tables:
        names = [c["name"] for c in cols[table]]
        query = 'SELECT %s FROM "%s"' % (",".join('"%s"' % n for n in names), table)
        cursor = conn.execute(query)
        insert = sql.SQL("INSERT INTO {} ({}) VALUES ({})").format(
            q(table), sql.SQL(",").join(q(n) for n in names),
            sql.SQL(",").join([sql.Placeholder()] * len(names))
        )
        while True:
            batch = cursor.fetchmany(250)
            if not batch:
                break
            cur.executemany(insert, [tuple(row) for row in batch])


def set_identity_sequences(cur, identity):
    for table, col in identity.items():
        cur.execute(
            sql.SQL("SELECT setval(pg_get_serial_sequence({}, {}), COALESCE((SELECT MAX({}) FROM {}), 1), {})").format(
                sql.Literal("public." + table), sql.Literal(col), q(col), q(table),
                sql.SQL("(SELECT COUNT(*)>0 FROM {})").format(q(table)),
            )
        )


def create_unique_indexes(cur, indexes):
    for table, name, cols, predicate, unique in indexes:
        if table == "works" and name == "idx_works_popular_v3":
            cur.execute("""CREATE INDEX pg_idx_works_popular_v3 ON works(
                status, (likes + 2 * favorites + forks) DESC, published_at_ms DESC
            )""")
            continue
        if not cols:
            raise ValueError("Index without columns: " + name)
        statement = sql.SQL("CREATE " + ("UNIQUE " if unique else "") + "INDEX {} ON {} ({})").format(
            q("pg_" + name[:58]), q(table),
            sql.SQL(",").join(q(col) for col in cols),
        )
        if predicate:
            statement += sql.SQL(" WHERE " + predicate)
        cur.execute(statement)


def create_foreign_keys(cur, fks):
    grouped = defaultdict(list)
    for table, row in fks:
        grouped[(table, row["id"])].append(row)
    for (table, idx), rows in grouped.items():
        rows.sort(key=lambda r: r["seq"])
        ref = rows[0]["table"]
        columns = [r["from"] for r in rows]
        targets = [r["to"] for r in rows]
        if any(not x for x in targets):
            raise ValueError("Foreign key depends on implicit SQLite rowid")
        on_delete = rows[0]["on_delete"].upper()
        if on_delete not in {"NO ACTION", "RESTRICT", "CASCADE", "SET NULL", "SET DEFAULT"}:
            raise ValueError("Unsupported foreign key action")
        cur.execute(sql.SQL(
            "ALTER TABLE {} ADD CONSTRAINT {} FOREIGN KEY ({}) REFERENCES {} ({}) "
            "ON DELETE " + on_delete + " DEFERRABLE INITIALLY DEFERRED"
        ).format(q(table), q("fk_" + table[:42] + "_" + str(idx)),
                 sql.SQL(",").join(q(c) for c in columns), q(ref),
                 sql.SQL(",").join(q(c) for c in targets)))


def verify_counts(cur, expected):
    for table, n in expected.items():
        cur.execute(sql.SQL("SELECT COUNT(*) FROM {}").format(q(table)))
        actual = cur.fetchone()[0]
        if actual != n:
            raise ValueError("Count mismatch for " + table + ": " + str(actual) + " vs " + str(n))


def _normalized_cell(value):
    from decimal import Decimal
    if isinstance(value, (bytes, bytearray, memoryview)):
        return {"binaryBase64": base64.b64encode(bytes(value)).decode("ascii")}
    if isinstance(value, Decimal):
        return int(value) if value == int(value) else float(value)
    return value


def _digest_rows(rows) -> tuple[int, int, int]:
    """Order-independent 256-bit row multiset checksum (sum + XOR).

    Including both sum and XOR prevents duplicate rows cancelling in pairs.
    Counts are checked separately. No raw row/password data is logged.
    """
    mod = (1 << 256) - 1
    total, xor, count = 0, 0, 0
    for row in rows:
        payload = json.dumps([_normalized_cell(v) for v in row],
                             ensure_ascii=False, separators=(",", ":"), default=str)
        h = int.from_bytes(hashlib.sha256(payload.encode("utf-8")).digest(), "big")
        total = (total + h) & mod
        xor ^= h
        count += 1
    return count, total, xor


def verify_content(cur, source, columns):
    """Compare every imported row, not just table counts."""
    for table, rows in columns.items():
        names = [c["name"] for c in rows]
        # Chunked cursors keep audit memory bounded on large snapshots.
        source_cursor = source.execute(
            "SELECT " + ",".join('"' + n + '"' for n in names) +
            ' FROM "' + table + '"'
        )
        source_digest = _digest_rows(source_cursor)
        cur.execute(sql.SQL("SELECT {} FROM {}").format(
            sql.SQL(",").join(q(n) for n in names), q(table)
        ))
        target_digest = _digest_rows(cur)
        if source_digest != target_digest:
            raise ValueError("Full-row data mismatch in table " + table)


def stage(source: Path, dsn: str, apply: bool) -> dict:
    conn, tables = read_snapshot(source)
    try:
        counts = _source_counts(conn, tables)
        if not counts.get("users"):
            raise ValueError("Source contains no legacy users; refusing an empty-account migration")
        cols, fks, indexes, identity = inspect_schema(conn, tables)
        result = {"tables": len(tables), "rows": sum(counts.values()),
                  "users": counts.get("users", 0),
                  "oauthIdentities": counts.get("oauth_identities", 0),
                  "sessions": counts.get("sessions", 0),
                  "schemaTriggersNotPorted": conn.execute(
                      "SELECT COUNT(*) FROM sqlite_master WHERE type='trigger'"
                  ).fetchone()[0],
                  "dryRun": not apply,
                  "sourceReadOnly": True,
                  "passwordHashesPreserved": True}
        if not apply:
            return result
        if not dsn:
            raise ValueError("PG staging URL is required")
        if psycopg is None:
            raise RuntimeError("Install psycopg[binary] before staging data")
        with psycopg.connect(dsn, autocommit=False, connect_timeout=5) as pg:
            with pg.cursor() as cur:
                cur.execute(
                    """SELECT COUNT(*) FROM information_schema.tables
                       WHERE table_schema='public' AND table_type='BASE TABLE'"""
                )
                if cur.fetchone()[0]:
                    raise ValueError("PostgreSQL target already contains tables; refusing overwrite")
                cur.execute("SET LOCAL lock_timeout = '5s'")
                cur.execute("SET LOCAL statement_timeout = '120s'")
                # citext preserves SQLite COLLATE NOCASE equality and unique-email rules.
                # This requires a DBA-approved PostgreSQL citext extension.
                cur.execute("CREATE EXTENSION IF NOT EXISTS citext")
                build_tables(cur, conn, tables, cols, identity)
                import_rows(cur, conn, tables, cols)
                set_identity_sequences(cur, identity)
                create_unique_indexes(cur, indexes)
                create_foreign_keys(cur, fks)
                verify_counts(cur, counts)
                verify_content(cur, conn, cols)
            pg.commit()
        result["checksumsVerified"] = True
        result["staged"] = True
        return result
    finally:
        conn.close()


def main(argv=None):
    parser = argparse.ArgumentParser(description="Read-only SQLite -> PostgreSQL staging migration")
    parser.add_argument("--sqlite-snapshot", required=True, type=Path)
    parser.add_argument("--apply-staging", action="store_true")
    args = parser.parse_args(argv)
    dsn = os.environ.get("HANDRAW_PG_STAGING_URL", "")
    if args.apply_staging:
        if os.environ.get("HANDRAW_ALLOW_PG_STAGING") != "YES":
            parser.error("Set HANDRAW_ALLOW_PG_STAGING=YES to explicitly allow staging")
        parsed = urlsplit(dsn)
        if parsed.scheme not in ("postgresql", "postgres") or not parsed.hostname:
            parser.error("HANDRAW_PG_STAGING_URL must be a valid PostgreSQL DSN")
    try:
        result = stage(args.sqlite_snapshot, dsn, args.apply_staging)
    except Exception as exc:
        print(json.dumps({"ok": False, "error": str(exc)}, ensure_ascii=False), file=sys.stderr)
        return 1
    print(json.dumps({"ok": True, **result}, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
