from ops.studio_official_approval_132 import CODES

HEX=re.compile(r"^[a-f0-9]{64}$")
SHA=re.compile(r"^[a-f0-9]{40}$")
IDENT=re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.:-]{2,79}$")
MAX_BYTES=1024*1024
SOURCES={
    "official":"website-editorial-webdb-skill",
    "postgres":"independent-pg17-physical-restore",
    "storage":"real-private-r2-s3-cdn",
    "redis":"real-two-instance-redis-failover",
    "provider":"final-vendor-finance-ledger",
}
CASE_IDS={
    "official":"web_db_and_skill_main_strict_parity",
    "postgres":"pg17_offline_backup_restore_rollback",
    "storage":"real_object_bucket_and_expired_url",
    "redis":"redis_multi_instance_failover",
    "provider":"real_provider_charge_refund_ledger",
}


def _utc(s, now):
    if not isinstance(s,str) or not s.endswith("Z") or len(s)>30:
        raise ValueError("UTC witness time required")
    try:
        d=datetime.fromisoformat(s.replace("Z","+00:00"))
    except ValueError:
        raise ValueError("invalid witness UTC") from None
    if d.utcoffset()!=timedelta(0) or d>now+timedelta(minutes=5) or now-d>timedelta(days=30):
        raise ValueError("stale or future witness")
    return d


def _private(path):
    p=Path(path)
    if p.is_symlink() or not p.is_file() or not 0<p.stat().st_size<=MAX_BYTES:
        raise ValueError("missing, linked or oversized proof")
    if os.name=="posix" and stat.S_IMODE(p.stat().st_mode)&0o077:
        raise ValueError("proof file must be private 0600")
    payload=p.read_bytes()
    try:
        doc=json.loads(payload.decode("utf-8"))
    except (UnicodeError,json.JSONDecodeError):
        raise ValueError("invalid proof JSON") from None
    return doc, hashlib.sha256(payload).hexdigest()


def _validate_report(kind,report):
    if not isinstance(report,dict) or report.get("decision")!="NO-GO":
        raise ValueError("witness may not claim autonomous GO")
    if kind=="official":
        return (report.get("signedCandidateClaims")==3 and
            report.get("strictParityDryRunPassed") is True and
            report.get("candidateCodes")==list(CODES) and
            report.get("automaticPromotionAuthorized") is False and
            report.get("websiteDbOriginIndependentlyProven") is False)
    if kind=="postgres":
        return (report.get("mode")=="isolated-postgres17-pitr-readonly-verified"
            and report.get("pg17ReplayPausedAndRowsMatched") is True and
            report.get("productionReleaseAuthorized") is False)
    if kind=="storage":
        x=report.get("observed")
        return (isinstance(x,dict) and
            all(x.get(k) is True for k in ("ownBytesMatched",
             "crossTenantReadDeniedBothDirections",
             "crossTenantWriteDeniedBothDirections","anonymousDenied",
             "expiredSignedUrlDenied")) and
            report.get("cdnOldUrlInvalidated") is True and
            report.get("revokedSignedUrlDenied") is True and
            report.get("restoredMediaBytesMatched") is True)
    if kind=="redis":
        return (report.get("crossClientAtomicNxObserved") is True and
            report.get("redisTenantAclDeniedBothDirections") is True and
            report.get("twoPhysicalWebInstancesIndependentlyProven") is True and
            report.get("automaticFailoverVerified") is True)
    if kind=="provider":
        return (report.get("result")=="NO_AUTOMATED_ANOMALIES" and
            report.get("anomalies")==[] and
            report.get("currencyUnitsSeparated") is True and
            report.get("externalStatementsAuthenticated") is False)
    raise ValueError("unknown witness kind")


def evaluate(registry,proofs,*,trust_sha,web_sha,skill_sha,now=None):
    """All complete results are documentary CLAIMS, never live D acceptance."""
    if not isinstance(web_sha,str) or not SHA.fullmatch(web_sha) or not isinstance(skill_sha,str) or not SHA.fullmatch(skill_sha):
        raise ValueError("full Web/Skill SHAs required")
    if not isinstance(trust_sha,str) or not HEX.fullmatch(trust_sha):
        raise ValueError("out-of-band pinned trust SHA256 required")
    now=now or datetime.now(timezone.utc)
    if (not isinstance(registry,dict) or
        set(registry)!={"schemaVersion","issuer","webSha","skillSha","environment","records"}
        or registry["schemaVersion"]!=1 or registry["issuer"]!="phase22-independent-auditor"
        or registry["environment"]!="preproduction"
        or registry["webSha"]!=web_sha or registry["skillSha"]!=skill_sha
        or not isinstance(registry["records"],list) or len(registry["records"])>len(SOURCES)):
        raise ValueError("invalid private externally anchored registry")
    # Hash canonical registry contents, so harmless formatting/line endings
    # do not make independent SHA fixtures accidentally ambiguous.
    canon=json.dumps(registry,sort_keys=True,separators=(",",":"),
                     ensure_ascii=False,allow_nan=False).encode("utf-8")
    if hashlib.sha256(canon).hexdigest()!=trust_sha:
        raise ValueError("untrusted external registry digest")
    if not isinstance(proofs,dict) or not set(proofs)<=set(SOURCES):
        raise ValueError("unrecognized private proof names")
    states={k:"MISSING" for k in SOURCES}
    seen=set();ids=set();operator_pairs=set()
    for row in registry["records"]:
        if (not isinstance(row,dict)
            or set(row)!={"kind","caseId","artifactSha256","sourceOrigin",
                          "operatorId","independentReviewerId","evidenceId",
                          "observedAtUtc","webSha","skillSha"}):
            raise ValueError("unexpected registry fields")
        kind=row["kind"]
        if kind not in SOURCES or kind in seen or row["caseId"]!=CASE_IDS[kind] or row["sourceOrigin"]!=SOURCES[kind]:
            raise ValueError("duplicate or cross-case witness")
        seen.add(kind)
        if row["webSha"]!=web_sha or row["skillSha"]!=skill_sha:
            raise ValueError("witness from stale deployment")
        if not isinstance(row["artifactSha256"],str) or not HEX.fullmatch(row["artifactSha256"]):
            raise ValueError("invalid proof SHA")
        for fld in ("operatorId","independentReviewerId","evidenceId"):
            if not isinstance(row[fld],str) or not IDENT.fullmatch(row[fld]):
                raise ValueError("invalid external witness identity")
        if row["operatorId"]==row["independentReviewerId"] or row["evidenceId"] in ids:
            raise ValueError("self review or replayed evidence id")
        ids.add(row["evidenceId"])
        # Different case-specific operators are allowed; a single operator
        # cannot act as their own reviewer on any individual evidence.
        operator_pairs.add((row["operatorId"],row["independentReviewerId"]))
        _utc(row["observedAtUtc"],now)
        entry=proofs.get(kind)
        if entry is None:
            states[kind]="MISSING_ARTIFACT"
            continue
        if not isinstance(entry,tuple) or len(entry)!=2:
            raise ValueError("untrusted private artifact carrier")
        report,digest=entry
        if digest!=row["artifactSha256"]:
            raise ValueError("independently pinned witness bytes have changed")
        states[kind]=("STRUCTURALLY_CONSISTENT_CLAIM" if _validate_report(kind,report)
                      else "INCOMPLETE_CLAIM")
    if any(k not in seen for k in proofs):
        raise ValueError("unregistered artifact cannot be accepted")
    return {"issue":132,"phase":22,"witnessStates":states,
            "pinnedWitnessCount":sum(v=="STRUCTURALLY_CONSISTENT_CLAIM" for v in states.values()),
            "realDPassCountVerifiedByThisTool":0,
            "sourceAuthenticityIndependentlyEstablished":False,
            "physicalHostIdentityIndependentlyEstablished":False,
            "websiteApprovalGranted":False,
            "publishedResourcesChanged":False,
            "releaseAuthorized":False,"decision":"NO-GO"}


def main(argv=None):
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--registry",type=Path)
    ap.add_argument("--proof-dir",type=Path)
    ap.add_argument("--web-sha",required=True)
    ap.add_argument("--skill-sha",required=True)
    ap.add_argument("--report",type=Path,required=True)
    args=ap.parse_args(argv)
    try:
        if args.report.exists() or args.report.is_symlink() or not args.report.parent.is_dir():
            raise ValueError("new private output path required")
        if (args.registry is None)!=(args.proof_dir is None):
            raise ValueError("registry and private proof dir must be supplied together")
        if args.registry is None:
            result={"phase":22,"issue":132,"witnessStates":{k:"MISSING" for k in SOURCES},
                    "pinnedWitnessCount":0,"realDPassCountVerifiedByThisTool":0,
                    "releaseAuthorized":False,"decision":"NO-GO"}
        else:
            root=args.proof_dir
            if root.is_symlink() or not root.is_dir():
                raise ValueError("unsafe private proof directory")
            registry,_=_private(args.registry)
            proofs={}
            for kind in SOURCES:
                p=root/(kind+".json")
                if p.exists() or p.is_symlink():
                    proofs[kind]=_private(p)
            result=evaluate(registry,proofs,trust_sha=os.environ.get(
                "HANDRAW_PHASE22_TRUST_SHA256",""),
                web_sha=args.web_sha,skill_sha=args.skill_sha)
        fd=os.open(args.report,os.O_WRONLY|os.O_CREAT|os.O_EXCL,0o600)
        with os.fdopen(fd,"w",encoding="utf-8") as out:
            json.dump(result,out,ensure_ascii=False,indent=2,sort_keys=True)
            out.write("\n")
        print("PHASE22 WITNESS "+json.dumps({"decision":"NO-GO",
              "claimsBound":result["pinnedWitnessCount"],"externalDPass":0}))
        return 0
    except Exception:
        print("Phase22 witness chain BLOCKED: incomplete or untrusted proof",file=sys.stderr)
        return 2


if __name__=="__main__":
    raise SystemExit(main())
