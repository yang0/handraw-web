/* Regression guard for the standalone account P1 navigation and auth UX. */
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const root = path.join(__dirname, "..");
const main = fs.readFileSync(path.join(root, "demo/assets/main-app.js"), "utf8");
const shared = fs.readFileSync(path.join(root, "demo/assets/shared.js"), "utf8");

assert.match(main, /function renderAccountSettingsPage\(root\)/, "account settings has its own view");
assert.match(main, /view === "account" \|\| \(view === "profile" && p\.get\("ptab"\) === "account"\)/, "legacy profile account URLs redirect");
assert.match(main, /App\.view === "account"\) renderAccountSettingsPage\(root\)/, "account route renders settings");
assert.match(main, /UI\.accountSection = snap\.accountSection \|\| UI\.accountSection/, "auth returns to selected account section");
assert.match(main, /node\.dataset\.accountPanel !== section\) node\.remove\(\)/, "irrelevant account panels are removed");
for (const panel of ["profile","security","devices"]) {
  assert.match(shared, new RegExp('data-account-panel="'+panel+'"'), panel + " section defined");
}
assert.ok(shared.includes('id="acc-avatar-confirm"'), "avatar upload requires confirmation");
assert.ok(shared.includes("pendingAvatar = file"), "selection only stages avatar");
assert.ok(shared.includes('avatarPreview.toDataURL("image/png")'), "upload uses approved square crop");
assert.ok(shared.includes("createImageBitmap(file"), "PNG decoding supports native image bitmap");
assert.ok(shared.includes("file.size > 3 * 1024 * 1024"), "original file over 3MB is rejected");
assert.ok(!shared.includes("最大 12 MB") && !shared.includes("file.size > 12 * 1024 * 1024"), "12MB source allowance has been removed");
assert.ok(shared.includes('role="status" aria-live="polite" aria-atomic="true"'), "avatar feedback is announced");
assert.ok(shared.includes('kind === "error" ? "alert" : "status"'), "errors announce with alert role");
assert.ok(shared.includes("图片解码失败") && shared.includes("图片读取失败"), "image processing errors are explicit");
assert.ok(shared.includes("头像上传失败："), "server rejection is visible");
assert.ok(shared.includes("图片尚未准备好"), "upload does not silently do nothing");
assert.ok(shared.includes("reader.readAsDataURL(file)"), "fallback decoding exists");
assert.ok(shared.includes('tabindex="0"'), "crop is keyboard accessible");
assert.ok(shared.includes('"pointerdown"') && shared.includes('"pointermove"') && shared.includes('"pointerup"'), "drag event lifecycle");
assert.ok(shared.includes("avatarPanX += dx"), "crop tracks pointer movement");
assert.ok(shared.includes('id="acc-avatar-center"'), "center reset exists");
assert.ok(shared.includes("restoreAuthDraft()"), "auth drafts persist across tabs");
assert.ok(shared.includes('event.key !== "Enter"'), "Enter submits auth form");
assert.ok(!main.includes('data-ptab="account"'), "account settings not in public profile tabs");
assert.ok(shared.includes("注册昵称与邀请码（选填）"), "registration nickname and invite code optional");
assert.ok(shared.includes("注册完成后昵称不可修改"), "registration explains permanent nickname");
assert.ok(!shared.includes('id="acc-display-name"'), "existing nickname immutable");
assert.ok(!shared.includes('data-account-panel="privacy"'), "closure panel unavailable");
assert.ok(!shared.includes('"/api/account/close"'), "closure is not called");
assert.ok(!main.includes('"reactivate"'), "reactivation page not routed");
assert.ok(shared.includes('data-account-panel="email"'), "email has dedicated section");
assert.ok(shared.includes('id="acc-send-email-verification"'), "verification inline");
const verificationPanel = shared.slice(shared.indexOf('<section data-account-panel="email"'), shared.indexOf('<section data-account-panel="security"', shared.indexOf('<section data-account-panel="email"')));
assert.ok(verificationPanel.indexOf('id="acc-email-verify-status"') >= 0 && verificationPanel.indexOf('id="acc-send-email-verification"') > verificationPanel.indexOf('id="acc-email-verify-status"'), "verification action sits immediately beside verification status");
assert.ok(verificationPanel.indexOf('id="acc-send-email-verification"') < verificationPanel.indexOf("更换绑定邮箱"), "verification action precedes email rebinding");
assert.equal((verificationPanel.match(/id="acc-send-email-verification"/g) || []).length, 1, "only one verification action");
assert.match(shared, /body: \{ currentPassword, newPassword \}/, "password change remains separate from profile update");
assert.doesNotMatch(shared.slice(shared.indexOf("function renderAccountSettingsFormHtml"), shared.indexOf("function bindAccountSettingsForm")), /view:"recovery"/, "recovery entry is only in logged-out flow");
console.log("Account navigation / registration regression guards passed");
