/* P2 product contract: all key entrypoints exist without reintroducing closure. */
"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const root = path.join(__dirname,"..");
const read = p => fs.readFileSync(path.join(root,p),"utf8");
const shared = read("demo/assets/shared.js");
const main = read("demo/assets/main-app.js");
const tools = read("demo/assets/account-tools.js");
const admin = read("demo/assets/admin-app.js");
const backend = read("backend/features.py");
const oauth = read("backend/p2_oauth.py");
const growth = read("backend/p2_growth.py");
const google = read("backend/p2_google.py");

assert.ok(shared.includes('id="github-auth-entry"'), "third-party auth exists in login / signup");
assert.ok(shared.includes('"/api/auth/providers"'), "login providers have a single capability endpoint");
assert.ok(shared.includes('id: "google"') && shared.includes('id: "github"'), "both provider entries are displayed");
assert.ok(shared.includes("尚未启用"), "unconfigured providers are not silently hidden");
assert.ok(shared.includes('"/api/auth/" + provider.id + "/start?mode=login"'), "login starts the actual provider");
assert.ok(shared.includes('"/api/auth/" + provider.id + "/start?mode=link"'), "account may link provider");
assert.ok(shared.includes('"/api/auth/" + provider.id + "/unlink"'), "account may unlink provider");
assert.ok(shared.includes('"/api/auth/funnel-event"'), "anonymous auth views are measured");
assert.ok(shared.includes('"signup_view"') && shared.includes('"signup_submit"'), "signup funnel events");
assert.ok(main.includes('"oauth-register"') && tools.includes('"oauth-register"'), "social signup confirmation routed");
assert.ok(tools.includes("/api/auth/github/signup-status"), "social signup requires proven provider identity");
assert.ok(tools.includes("注册后不可修改"), "social signup warns about permanent creator nickname");
assert.ok(tools.includes("/api/auth/github/finish-signup"), "explicit social signup submit exists");
assert.ok(oauth.includes("oauth_signup_tickets"), "signup ticket is short-lived and stored server-side");
assert.ok(google.includes("code_challenge_method") && google.includes("S256"), "Google OAuth uses PKCE");
assert.ok(google.includes("email_verified") && google.includes("openidconnect.googleapis.com"), "Google verified userinfo is checked");
assert.ok(backend.includes('"/api/auth/google/callback"'), "Google callback is wired");
assert.ok(oauth.includes("browser_nonce_hash"), "state is bound to browser");
assert.ok(oauth.includes("compare_digest"), "browser nonce is checked with constant-time comparison");
assert.ok(oauth.includes("DELETE FROM oauth_flows WHERE state_hash"), "OAuth state cannot replay");
assert.ok(oauth.includes('code="oauth_link_required"'), "email collision requires explicit linking");
assert.ok(!oauth.includes("password_hash = token"), "OAuth access tokens are not used as local password");
assert.ok(shared.includes('id="acc-export-data"'), "user can request full account data");
assert.ok(shared.includes("nextPage"), "export continues across pages");
assert.ok(admin.includes("/api/admin/growth?days=30"), "admin dashboard fetches growth metrics");
assert.ok(admin.includes("activationRate") && admin.includes("retentionD7Rate"), "growth metrics displayed");
assert.ok(growth.includes("first_collection") && growth.includes("first_generation"), "activation events included");
assert.ok(growth.includes("eligible_d7"), "retention denominator excludes immature cohorts");
assert.ok(backend.includes("try_send_security_alert"), "security email implemented");
assert.ok(backend.includes("password_reused"), "recovery rejects old passwords");
assert.ok(!shared.includes('id="acc-close-account"'), "account closure is not exposed");
assert.ok(!backend.includes('req_path == "/api/account/close"'), "account closure stays disabled");
assert.ok(!main.includes('"reactivate"'), "account reactivation remains disabled");
assert.ok(!shared.includes('id="acc-display-name"'), "nickname immutable after registration");
console.log("P2 social identity / growth / safety UI guards passed");
