"use strict";
const assert=require("node:assert/strict");
const V=require("../demo/assets/studio-make-image-versions.js");
const spec={subject:"初稿",style:{id:"FA-001"},ratio:"3:4"};
const first={mediaId:"m-1",imageUrl:"/generated/one.webp",runId:"r1"};
const history=V.merge([], [first], {runId:"r1",runSpec:spec});
assert.equal(history.length,1);
assert.equal(history[0].recipeSnapshot.subject,"初稿");
spec.subject="下轮草稿";
const next=V.merge(history,[{item:{mediaId:"m-2",imageUrl:"/generated/two.webp",runId:"r2"}}],{runId:"r2",runSpec:{subject:"新稿"}});
assert.equal(next.length,2);
assert.equal(next[0].recipeSnapshot.subject,"初稿");
assert.equal(next[1].recipeSnapshot.subject,"新稿");
assert.equal(V.select(next,"m-1").mediaId,"m-1");
assert.equal(V.select(next,"gone").mediaId,"m-2");
assert.equal(V.merge(next,[first]).length,2,"resuming same Run is idempotent");
assert.equal(V.merge(next,[{imageUrl:"blob:local",mediaId:"ghost"}]).length,2);
assert.equal(V.merge(next,[{imageUrl:"/preview.webp"}]).length,2);
console.log("Studio Make Image 2.0 version persistence tests passed");
